#ifndef COVE_NEXT_SDL3_SHIM_H
#define COVE_NEXT_SDL3_SHIM_H

#include <SDL3/SDL.h>

#if defined(__APPLE__)
#include <SDL3/SDL_metal.h>
#endif

// Window flags
enum {
	COVE_SDL_WINDOW_RESIZABLE = SDL_WINDOW_RESIZABLE,
	COVE_SDL_WINDOW_HIGH_PIXEL_DENSITY = SDL_WINDOW_HIGH_PIXEL_DENSITY,
	COVE_SDL_WINDOW_METAL = SDL_WINDOW_METAL,
	COVE_SDL_WINDOW_BORDERLESS = SDL_WINDOW_BORDERLESS,
	COVE_SDL_WINDOW_MAXIMIZED = SDL_WINDOW_MAXIMIZED,
	COVE_SDL_WINDOW_HIDDEN = SDL_WINDOW_HIDDEN,
};

// Application / window lifecycle events
enum {
	COVE_SDL_EVENT_QUIT = SDL_EVENT_QUIT,
	COVE_SDL_EVENT_WINDOW_RESIZED = SDL_EVENT_WINDOW_RESIZED,
	COVE_SDL_EVENT_WINDOW_PIXEL_SIZE_CHANGED = SDL_EVENT_WINDOW_PIXEL_SIZE_CHANGED,
	COVE_SDL_EVENT_WINDOW_METAL_VIEW_RESIZED = SDL_EVENT_WINDOW_METAL_VIEW_RESIZED,
	COVE_SDL_EVENT_WINDOW_CLOSE_REQUESTED = SDL_EVENT_WINDOW_CLOSE_REQUESTED,
	COVE_SDL_EVENT_WINDOW_DESTROYED = SDL_EVENT_WINDOW_DESTROYED,
	COVE_SDL_EVENT_WINDOW_EXPOSED = SDL_EVENT_WINDOW_EXPOSED,
	COVE_SDL_EVENT_WINDOW_MINIMIZED = SDL_EVENT_WINDOW_MINIMIZED,
	COVE_SDL_EVENT_WINDOW_RESTORED = SDL_EVENT_WINDOW_RESTORED,
	COVE_SDL_EVENT_WINDOW_FOCUS_GAINED = SDL_EVENT_WINDOW_FOCUS_GAINED,
	COVE_SDL_EVENT_WINDOW_FOCUS_LOST = SDL_EVENT_WINDOW_FOCUS_LOST,
	COVE_SDL_EVENT_WINDOW_OCCLUDED = SDL_EVENT_WINDOW_OCCLUDED,
	// Internal wake signal used to interrupt SDL_WaitEventTimeout when work is
	// posted from the render thread or another native callback.
	COVE_SDL_EVENT_WAKE = SDL_EVENT_USER,
};

// Keyboard events
enum {
	COVE_SDL_EVENT_KEY_DOWN = SDL_EVENT_KEY_DOWN,
	COVE_SDL_EVENT_KEY_UP   = SDL_EVENT_KEY_UP,
	COVE_SDL_EVENT_TEXT_EDITING = SDL_EVENT_TEXT_EDITING,
	COVE_SDL_EVENT_TEXT_INPUT = SDL_EVENT_TEXT_INPUT,
};

// Mouse events
enum {
	COVE_SDL_EVENT_MOUSE_MOTION      = SDL_EVENT_MOUSE_MOTION,
	COVE_SDL_EVENT_MOUSE_BUTTON_DOWN = SDL_EVENT_MOUSE_BUTTON_DOWN,
	COVE_SDL_EVENT_MOUSE_BUTTON_UP   = SDL_EVENT_MOUSE_BUTTON_UP,
	COVE_SDL_EVENT_MOUSE_WHEEL       = SDL_EVENT_MOUSE_WHEEL,
};

// Touch / finger events. SDL3 reports these in window-normalized [0,1] coords,
// so the shell multiplies by the window's logical size to land in the same
// coordinate space as mouse events.
enum {
	COVE_SDL_EVENT_FINGER_DOWN   = SDL_EVENT_FINGER_DOWN,
	COVE_SDL_EVENT_FINGER_MOTION = SDL_EVENT_FINGER_MOTION,
	COVE_SDL_EVENT_FINGER_UP     = SDL_EVENT_FINGER_UP,
};

// Keyboard modifier masks (SDL_Keymod is typedef Uint16; #defines not imported by Swift)
enum {
	COVE_SDL_KMOD_LSHIFT = SDL_KMOD_LSHIFT,
	COVE_SDL_KMOD_RSHIFT = SDL_KMOD_RSHIFT,
	COVE_SDL_KMOD_LCTRL  = SDL_KMOD_LCTRL,
	COVE_SDL_KMOD_RCTRL  = SDL_KMOD_RCTRL,
	COVE_SDL_KMOD_LALT   = SDL_KMOD_LALT,
	COVE_SDL_KMOD_RALT   = SDL_KMOD_RALT,
	COVE_SDL_KMOD_LGUI   = SDL_KMOD_LGUI,
	COVE_SDL_KMOD_RGUI   = SDL_KMOD_RGUI,
};

// Mouse buttons (#defines not imported by Swift)
enum {
	COVE_SDL_BUTTON_LEFT   = SDL_BUTTON_LEFT,
	COVE_SDL_BUTTON_MIDDLE = SDL_BUTTON_MIDDLE,
	COVE_SDL_BUTTON_RIGHT  = SDL_BUTTON_RIGHT,
	COVE_SDL_BUTTON_X1     = SDL_BUTTON_X1,
	COVE_SDL_BUTTON_X2     = SDL_BUTTON_X2,
};

// Mouse wheel direction
enum {
	COVE_SDL_MOUSEWHEEL_FLIPPED = SDL_MOUSEWHEEL_FLIPPED,
};

// Gamepad events
enum {
    COVE_SDL_EVENT_GAMEPAD_AXIS_MOTION = SDL_EVENT_GAMEPAD_AXIS_MOTION,
    COVE_SDL_EVENT_GAMEPAD_BUTTON_DOWN = SDL_EVENT_GAMEPAD_BUTTON_DOWN,
    COVE_SDL_EVENT_GAMEPAD_BUTTON_UP   = SDL_EVENT_GAMEPAD_BUTTON_UP,
    COVE_SDL_EVENT_GAMEPAD_ADDED       = SDL_EVENT_GAMEPAD_ADDED,
    COVE_SDL_EVENT_GAMEPAD_REMOVED     = SDL_EVENT_GAMEPAD_REMOVED,
};

// Audio subsystem constants (#define / pointer-cast macros not imported by Swift).
static const Uint32 COVE_SDL_INIT_AUDIO = SDL_INIT_AUDIO;
static const SDL_AudioDeviceID COVE_SDL_AUDIO_DEVICE_DEFAULT_PLAYBACK = SDL_AUDIO_DEVICE_DEFAULT_PLAYBACK;

// System cursor identifiers (SDL_SystemCursor enum is not imported as raw ints by Swift).
enum {
	COVE_SDL_SYSTEM_CURSOR_DEFAULT      = SDL_SYSTEM_CURSOR_DEFAULT,
	COVE_SDL_SYSTEM_CURSOR_TEXT         = SDL_SYSTEM_CURSOR_TEXT,
	COVE_SDL_SYSTEM_CURSOR_WAIT         = SDL_SYSTEM_CURSOR_WAIT,
	COVE_SDL_SYSTEM_CURSOR_CROSSHAIR    = SDL_SYSTEM_CURSOR_CROSSHAIR,
	COVE_SDL_SYSTEM_CURSOR_PROGRESS     = SDL_SYSTEM_CURSOR_PROGRESS,
	COVE_SDL_SYSTEM_CURSOR_NWSE_RESIZE  = SDL_SYSTEM_CURSOR_NWSE_RESIZE,
	COVE_SDL_SYSTEM_CURSOR_NESW_RESIZE  = SDL_SYSTEM_CURSOR_NESW_RESIZE,
	COVE_SDL_SYSTEM_CURSOR_EW_RESIZE    = SDL_SYSTEM_CURSOR_EW_RESIZE,
	COVE_SDL_SYSTEM_CURSOR_NS_RESIZE    = SDL_SYSTEM_CURSOR_NS_RESIZE,
	COVE_SDL_SYSTEM_CURSOR_MOVE         = SDL_SYSTEM_CURSOR_MOVE,
	COVE_SDL_SYSTEM_CURSOR_NOT_ALLOWED  = SDL_SYSTEM_CURSOR_NOT_ALLOWED,
	COVE_SDL_SYSTEM_CURSOR_POINTER      = SDL_SYSTEM_CURSOR_POINTER,
};

// The platform shell owns SDL main integration; callers only supply application content.
typedef int (*CoveSDLAppMain)(void *);
int cove_sdl_run_app(CoveSDLAppMain entry, void *context);

#endif  // COVE_NEXT_SDL3_SHIM_H

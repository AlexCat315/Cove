//! Generates the embedded tables for the served Inspector assets.
//!
//! `crates/devtools/client/manifest.json` is the single source of truth for
//! which parts compose `/index.html`, `/inspector.css` and `/inspector.js` and
//! in what order. Nothing about those lists is restated in Rust: this build
//! script validates each bundle against the files on disk and emits the
//! `include_str!` tables into `OUT_DIR`, so adding, splitting, renaming or
//! reordering a part is a manifest edit only.

use std::collections::BTreeSet;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=COVE_DEVTOOLS_ESBUILD");
    println!("cargo:rustc-check-cfg=cfg(cove_packed_inspector)");
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let client_dir = manifest_dir.join("../devtools/client");
    let manifest_path = client_dir.join("manifest.json");
    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!("cargo:rerun-if-changed={}", client_dir.display());

    let manifest = fs::read_to_string(&manifest_path)
        .unwrap_or_else(|error| fail(&format!("cannot read {}: {error}", manifest_path.display())));
    let manifest: serde_json::Value = serde_json::from_str(&manifest).unwrap_or_else(|error| {
        fail(&format!(
            "{} is not valid JSON: {error}",
            manifest_path.display()
        ))
    });
    if let Some(esbuild) = env::var_os("COVE_DEVTOOLS_ESBUILD") {
        let modules = &manifest["modules"];
        let root = string_field(modules, "root");
        let parts = modules["parts"]
            .as_array()
            .unwrap_or_else(|| fail("missing module parts"));
        let entry = parts
            .iter()
            .map(|part| {
                let part = part
                    .as_str()
                    .unwrap_or_else(|| fail("module path must be a string"));
                let absolute = safe_join(&safe_join(&client_dir, &root), part);
                format!(
                    "import {};\n",
                    serde_json::to_string(&absolute).expect("serializable module path")
                )
            })
            .collect::<String>();
        let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
        let entry_path = out.join("inspector-entry.mjs");
        fs::write(&entry_path, entry).unwrap_or_else(|error| fail(&error.to_string()));
        let packed = out.join("inspector.bundle.js");
        let mut output = std::ffi::OsString::from("--outfile=");
        output.push(&packed);
        let status = std::process::Command::new(esbuild)
            .arg(entry_path)
            .args([
                "--bundle",
                "--format=esm",
                "--platform=browser",
                "--log-level=warning",
            ])
            .arg(output)
            .status()
            .unwrap_or_else(|error| fail(&format!("cannot run COVE_DEVTOOLS_ESBUILD: {error}")));
        if !status.success() {
            fail("could not bundle Inspector modules");
        }
        println!("cargo:rustc-cfg=cove_packed_inspector");
    }
    let bundles = manifest["bundles"]
        .as_array()
        .unwrap_or_else(|| fail("manifest.json must define a `bundles` array"));
    if bundles.is_empty() {
        fail("`bundles` is empty; nothing would be served");
    }

    let mut generated = String::new();
    generated
        .push_str("// @generated by crates/devtools-cli/build.rs from client/manifest.json.\n");
    generated.push_str("// Bundled routes are the byte-for-byte concatenation of their parts.\n");
    generated.push_str("// CLIENT_MODULES is the ES module set behind /inspector.js: the route\n");
    generated.push_str("// itself is a generated entry importing every part, and each part is\n");
    generated.push_str("// served on its own so `import`/`export` work across the module graph.\n");
    generated.push_str("const CLIENT_BUNDLES: &[(&str, &str, &[(&str, &str)])] = &[\n");

    let mut routes = BTreeSet::new();
    for bundle in bundles {
        let route = string_field(bundle, "path");
        let root = string_field(bundle, "root");
        let media = string_field(bundle, "media");
        if !route.starts_with('/') || route.contains("..") {
            fail(&format!(
                "bundle path `{route}` must be an absolute route without `..`"
            ));
        }
        if !routes.insert(route.clone()) {
            fail(&format!("bundle path `{route}` is declared twice"));
        }
        let root_path = safe_join(&client_dir, &root);
        if !root_path.is_dir() {
            fail(&format!(
                "bundle root `{root}` is not a directory under client/"
            ));
        }
        let extension = Path::new(&route)
            .extension()
            .and_then(|value| value.to_str())
            .unwrap_or_else(|| fail(&format!("bundle path `{route}` has no file extension")));

        let parts: Vec<String> = bundle["parts"]
            .as_array()
            .unwrap_or_else(|| fail(&format!("bundle `{route}` must define a `parts` array")))
            .iter()
            .map(|value| {
                value
                    .as_str()
                    .unwrap_or_else(|| fail(&format!("bundle `{route}` parts must be strings")))
                    .to_owned()
            })
            .collect();
        if parts.is_empty() {
            fail(&format!("bundle `{route}` has no parts"));
        }

        let mut listed = BTreeSet::new();
        for part in &parts {
            if !listed.insert(part.as_str()) {
                fail(&format!("bundle `{route}` lists `{part}` twice"));
            }
            let path = safe_join(&root_path, part);
            if !path.is_file() {
                fail(&format!(
                    "bundle `{route}` lists `{part}` but {} is missing",
                    path.display()
                ));
            }
            if path.extension().and_then(|value| value.to_str()) != Some(extension) {
                fail(&format!(
                    "bundle `{route}` lists `{part}`, which is not a .{extension} part"
                ));
            }
            println!("cargo:rerun-if-changed={}", path.display());
        }

        // Drift guard: a file that exists but is not listed would never reach the
        // browser, which fails silently at runtime. Fail the build instead.
        let mut unlisted = Vec::new();
        collect_parts(&root_path, &root_path, extension, &mut unlisted);
        unlisted.retain(|path| !listed.contains(path.as_str()));
        if !unlisted.is_empty() {
            fail(&format!(
                "bundle `{route}` does not list: {}\nadd them to client/manifest.json in bundle order",
                unlisted.join(", ")
            ));
        }

        let _ = writeln!(generated, "    ({route:?}, {media:?}, &[");
        for part in &parts {
            let absolute = safe_join(&root_path, part);
            let absolute = absolute
                .to_str()
                .unwrap_or_else(|| fail(&format!("part path is not valid UTF-8: {absolute:?}")));
            let _ = writeln!(generated, "        ({part:?}, include_str!({absolute:?})),");
        }
        generated.push_str("    ]),\n");
    }
    generated.push_str("];\n");

    // The module set is validated like a bundle, but its parts are served
    // individually, so the generated table maps each part's relative path to
    // its bytes. The entry route is synthesized at request time from that list.
    let modules = manifest
        .get("modules")
        .unwrap_or_else(|| fail("manifest.json must define a `modules` object"));
    let route = string_field(modules, "path");
    let root = string_field(modules, "root");
    let media = string_field(modules, "media");
    if !route.starts_with('/') || route.contains("..") {
        fail(&format!(
            "modules path `{route}` must be an absolute route without `..`"
        ));
    }
    if !routes.insert(route.clone()) {
        fail(&format!(
            "modules path `{route}` is already served by a bundle"
        ));
    }
    let root_path = safe_join(&client_dir, &root);
    if !root_path.is_dir() {
        fail(&format!(
            "modules root `{root}` is not a directory under client/"
        ));
    }

    let parts: Vec<String> = modules["parts"]
        .as_array()
        .unwrap_or_else(|| fail(&format!("modules `{route}` must define a `parts` array")))
        .iter()
        .map(|value| {
            value
                .as_str()
                .unwrap_or_else(|| fail(&format!("modules `{route}` parts must be strings")))
                .to_owned()
        })
        .collect();
    if parts.is_empty() {
        fail(&format!("modules `{route}` has no parts"));
    }

    let mut listed = BTreeSet::new();
    for part in &parts {
        if !listed.insert(part.as_str()) {
            fail(&format!("modules `{route}` lists `{part}` twice"));
        }
        let path = safe_join(&root_path, part);
        if !path.is_file() {
            fail(&format!(
                "modules `{route}` lists `{part}` but {} is missing",
                path.display()
            ));
        }
        if path.extension().and_then(|value| value.to_str()) != Some("js") {
            fail(&format!(
                "modules `{route}` lists `{part}`, which is not a .js module"
            ));
        }
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let mut unlisted = Vec::new();
    collect_parts(&root_path, &root_path, "js", &mut unlisted);
    unlisted.retain(|path| !listed.contains(path.as_str()));
    if !unlisted.is_empty() {
        fail(&format!(
            "modules `{route}` does not list: {}\nadd them to client/manifest.json in module order",
            unlisted.join(", ")
        ));
    }

    let _ = writeln!(
        generated,
        "const CLIENT_MODULES: (&str, &str, &str, &[(&str, &str)]) = ({route:?}, {root:?}, {media:?}, &["
    );
    for part in &parts {
        let absolute = safe_join(&root_path, part);
        let absolute = absolute
            .to_str()
            .unwrap_or_else(|| fail(&format!("module path is not valid UTF-8: {absolute:?}")));
        let _ = writeln!(generated, "    ({part:?}, include_str!({absolute:?})),");
    }
    generated.push_str("]);\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let target = out_dir.join("client_bundles.rs");
    let previous = fs::read_to_string(&target).ok();
    if previous.as_deref() != Some(generated.as_str()) {
        fs::write(&target, generated)
            .unwrap_or_else(|error| fail(&format!("cannot write {}: {error}", target.display())));
    }
}

fn string_field(bundle: &serde_json::Value, key: &str) -> String {
    bundle[key]
        .as_str()
        .unwrap_or_else(|| fail(&format!("every bundle must define a string `{key}`")))
        .to_owned()
}

/// Joins a manifest-relative path, refusing traversal out of the root.
fn safe_join(root: &Path, relative: &str) -> PathBuf {
    let path = Path::new(relative);
    if path.is_absolute()
        || path
            .components()
            .any(|component| !matches!(component, std::path::Component::Normal(_)))
    {
        fail(&format!("`{relative}` must be a plain relative path"));
    }
    root.join(path)
}

/// Collects every file with `extension` under `dir`, relative to `root`.
fn collect_parts(root: &Path, dir: &Path, extension: &str, found: &mut Vec<String>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) => fail(&format!("cannot list {}: {error}", dir.display())),
    };
    for entry in entries {
        let entry =
            entry.unwrap_or_else(|error| fail(&format!("cannot list {}: {error}", dir.display())));
        let path = entry.path();
        if path.is_dir() {
            collect_parts(root, &path, extension, found);
        } else if path.extension().and_then(|value| value.to_str()) == Some(extension) {
            match path
                .strip_prefix(root)
                .ok()
                .and_then(|value| value.to_str())
            {
                Some(relative) => found.push(relative.replace('\\', "/")),
                None => fail(&format!("part path is not valid UTF-8: {path:?}")),
            }
        }
    }
}

fn fail(message: &str) -> ! {
    panic!("Inspector client manifest error: {message}");
}

//! Generates the Inspector client bundle table for `include_str!`.
//!
//! `crates/devtools/client/src/manifest.json` is the single source of truth for
//! which source parts compose the served `/inspector.js` and in what order.
//! Nothing about that list is restated in Rust: this build script validates the
//! manifest against the files on disk and emits the `include_str!` table into
//! `OUT_DIR`, so adding, splitting or reordering a part is a manifest edit only.

use std::collections::BTreeSet;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const MANIFEST_RELATIVE: &str = "src/manifest.json";
const PART_EXTENSION: &str = "js";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let client_dir = manifest_dir.join("../devtools/client");
    let source_dir = client_dir.join("src");
    let manifest_path = source_dir.join("manifest.json");
    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!("cargo:rerun-if-changed={}", source_dir.display());

    let manifest = fs::read_to_string(&manifest_path).unwrap_or_else(|error| {
        fail(&format!(
            "cannot read {}: {error}",
            manifest_path.display()
        ))
    });
    let manifest: serde_json::Value = serde_json::from_str(&manifest)
        .unwrap_or_else(|error| fail(&format!("{} is not valid JSON: {error}", manifest_path.display())));
    let parts: Vec<String> = manifest["parts"]
        .as_array()
        .unwrap_or_else(|| fail(&format!("{} must define a `parts` array", MANIFEST_RELATIVE)))
        .iter()
        .map(|value| {
            value
                .as_str()
                .unwrap_or_else(|| fail("every entry of `parts` must be a string path"))
                .to_owned()
        })
        .collect();

    if parts.is_empty() {
        fail("`parts` is empty; the served /inspector.js would have no source");
    }

    let mut seen = BTreeSet::new();
    for part in &parts {
        if !seen.insert(part.as_str()) {
            fail(&format!("`{part}` is listed twice; the bundle would duplicate it"));
        }
        let path = source_dir.join(part);
        if !path.is_file() {
            fail(&format!("`{part}` is listed in {MANIFEST_RELATIVE} but missing on disk"));
        }
        if Path::new(part).extension().and_then(|value| value.to_str()) != Some(PART_EXTENSION) {
            fail(&format!("`{part}` is not a .{PART_EXTENSION} source part"));
        }
        println!("cargo:rerun-if-changed={}", path.display());
    }

    // Drift guard: a source file that exists but is not listed would never reach
    // the browser, which fails silently at runtime. Fail the build instead.
    let mut unlisted = Vec::new();
    collect_parts(&source_dir, &source_dir, &mut unlisted);
    unlisted.retain(|path| !seen.contains(path.as_str()));
    if !unlisted.is_empty() {
        fail(&format!(
            "unlisted source parts in {}/: {}\nadd them to {} in bundle order",
            source_dir.display(),
            unlisted.join(", "),
            MANIFEST_RELATIVE
        ));
    }

    let mut generated = String::new();
    generated.push_str("// @generated by crates/devtools-cli/build.rs from client/src/manifest.json.\n");
    generated.push_str("// Ordered source parts of the Inspector ES module. The served /inspector.js\n");
    generated.push_str("// is their byte-for-byte concatenation, so the browser sees one module scope.\n");
    generated.push_str("const INSPECTOR_PARTS: &[(&str, &str)] = &[\n");
    for part in &parts {
        let absolute = source_dir.join(part);
        let absolute = absolute.to_str().unwrap_or_else(|| {
            fail(&format!("source part path is not valid UTF-8: {absolute:?}"))
        });
        let _ = writeln!(
            generated,
            "    ({part:?}, include_str!({absolute:?})),"
        );
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let target = out_dir.join("inspector_parts.rs");
    let previous = fs::read_to_string(&target).ok();
    if previous.as_deref() != Some(generated.as_str()) {
        fs::write(&target, generated)
            .unwrap_or_else(|error| fail(&format!("cannot write {}: {error}", target.display())));
    }
}

/// Collects every source part under `dir`, relative to `root`, in path order.
fn collect_parts(root: &Path, dir: &Path, found: &mut Vec<String>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) => fail(&format!("cannot list {}: {error}", dir.display())),
    };
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| fail(&format!("cannot list {}: {error}", dir.display())));
        let path = entry.path();
        if path.is_dir() {
            collect_parts(root, &path, found);
        } else if path.extension().and_then(|value| value.to_str()) == Some(PART_EXTENSION) {
            match path.strip_prefix(root).ok().and_then(|value| value.to_str()) {
                Some(relative) => found.push(relative.replace('\\', "/")),
                None => fail(&format!("source part path is not valid UTF-8: {path:?}")),
            }
        }
    }
}

fn fail(message: &str) -> ! {
    panic!("Inspector client manifest error: {message}");
}

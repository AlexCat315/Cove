import Foundation

// MARK: - Backing store

/// Reference-type storage for a `@State` property.
///
/// `@usableFromInline` so the compiler can inline `State`'s accessors
/// while keeping the type internal (not part of the public API surface).
@usableFromInline
final class StateStorage<Value>: @unchecked Sendable {
    var value: Value
    /// Called immediately after `value` is mutated. Wired by the composition scope.
    var onChange: (() -> Void)?
    var ownerScope: ObjectIdentifier?
    var preciseOwner = false
    let readersLock = NSLock()
    var readers: [ObjectIdentifier: Reader] = [:]

    init(value: Value) {
        self.value = value
    }
}

// MARK: - @State

/// A property wrapper for view-local mutable state.
///
/// Writing `wrappedValue` fires `StateStorage.onChange`, which the composition
/// runtime connects to `Recomposer.invalidate(scopeID:body:)`.
///
/// ```swift
/// @State var count = 0
/// Button("Tap") { count += 1 }   // triggers recompose of the owning scope
/// ```
@propertyWrapper
public struct State<Value>: DynamicProperty {

    @usableFromInline
    internal let _storage: StateStorage<Value>
    private let inspectionSummary: ((Value) -> String)?

    /// Explicitly opt a value into read-only DevTools observation. A custom
    /// summary can redact secrets or abbreviate a large application value.
    public init(wrappedValue: Value, expose: Bool = false, summary: ((Value) -> String)? = nil) {
        _storage = StateStorage(value: wrappedValue)
        inspectionSummary = expose ? (summary ?? { String(describing: $0) }) : nil
    }

    public var _devToolsValueType: String { String(reflecting: Value.self) }

    public var _devToolsRead: (() -> String)? {
        guard let inspectionSummary else { return nil }
        return { [weak storage = _storage] in
            storage.map { inspectionSummary($0.value) } ?? "<released>"
        }
    }

    public var wrappedValue: Value {
        get { _storage.readWhole(); return _storage.value }
        nonmutating set { _storage.set(newValue) }
    }

    /// Use `$property` to pass a `Binding` to child views.
    public var projectedValue: Binding<Value> {
        Binding(
            get: { self._storage.readWhole(); return self._storage.value },
            set: { self._storage.set($0) }
        )
    }

    /// Generated by `@TrackStateReads`; whole-value access remains available via `wrappedValue`.
    public subscript<Field>(tracking keyPath: KeyPath<Value, Field>, name name: String) -> Field {
        _storage.read(keyPath, name: name)
    }

    public subscript<Field>(tracking keyPath: WritableKeyPath<Value, Field>, name name: String) -> Field {
        get { _storage.read(keyPath, name: name) }
        nonmutating set {
            var copy = _storage.value
            copy[keyPath: keyPath] = newValue
            _storage.set(copy)
        }
    }

    /// Explicitly register an unread field as an invalidation signal: a write that
    /// changes this field invalidates the owning scope even when the body never
    /// reads it. Equivalent to a field read for invalidation purposes, but the
    /// value can be ignored. Useful when a view wants precise tracking of the
    /// fields it reads yet still react to an unrelated field.
    public subscript<Field>(signal keyPath: KeyPath<Value, Field>, name name: String) -> Field {
        _storage.readSignal(keyPath, name: name)
    }

    /// Element-level tracking for `state.items[i]`. The returned value is the
    /// element itself (concrete type preserved), and the owning scope is
    /// invalidated only when the element at `index` changes — writes to other
    /// indices or other fields leave it untouched. Generated by `@TrackStateReads`
    /// when it sees a subscript on a tracked array field.
    public subscript<Element>(trackingElement keyPath: WritableKeyPath<Value, [Element]>, at index: Int, name name: String) -> Element {
        _storage.readElement(keyPath, at: index, name: name)
    }

    /// Element-level tracking for `state.dict[key]`. Returns the optional element
    /// (matching `Dictionary`'s own subscript) and invalidates only when
    /// `dict[key]` actually changes. Generated by `@TrackStateReads` for tracked
    /// dictionary fields.
    public subscript<Key: Hashable, Element>(trackingElement keyPath: WritableKeyPath<Value, [Key: Element]>, at key: Key, name name: String) -> Element? {
        _storage.readElement(keyPath, at: key, name: name)
    }

    /// Fallback for subscripts on a tracked field whose element type is neither an
    /// array nor a dictionary (e.g. a custom subscriptable type). It degrades to
    /// whole-field tracking — the field's entire value is observed, so any write
    /// to it invalidates, just as before element tracking existed. This keeps
    /// `@TrackStateReads` compiling and behaving correctly for all subscriptable
    /// field types; only the granularity is coarser.
    public subscript<Field>(trackingElement keyPath: WritableKeyPath<Value, Field>, at index: Any, name name: String) -> Field {
        _storage.read(keyPath, name: name)
    }

    public func _setReadTrackingOwner(_ scope: ObjectIdentifier, precise: Bool) {
        _storage.ownerScope = scope
        _storage.preciseOwner = precise
    }

    // MARK: - ViewGraph escape hatch (Phase 6.2)

    /// Identity of the underlying storage — `ViewGraph` uses this as a stable
    /// scope key across body re-evaluations.
    public var _storageIdentity: ObjectIdentifier {
        ObjectIdentifier(_storage)
    }

    /// Install (or clear) the change observer. `ViewGraph` wires this to
    /// `Recomposer.invalidate` so writes trigger a recompose.
    public func _setOnChange(_ handler: (() -> Void)?) {
        _storage.onChange = handler
    }

    /// Copy the underlying value from `other` into this state's storage,
    /// without firing `onChange`. Used by `ViewGraph` when a parent recompose
    /// produces a new view value at the same slot — the new view's @State
    /// would otherwise reset to its initial value.
    public func _copyRuntimeValue(from other: State<Value>) {
        _storage.value = other._storage.value
    }
}

// MARK: - Sendable

// State is Sendable when the wrapped value is. StateStorage is already
// @unchecked Sendable, and writes are safe from any thread because
// StateStorage propagates through the recomposer (main-thread queue).
extension State: @unchecked Sendable where Value: Sendable {}

internal import Foundation
private import ToolSupport

struct ProjectTaskRunner {
    let arguments: Arguments
    let sdk: URL

    func run() throws {
        guard let workspace = try ProjectWorkspace.find(from: arguments.directory) else {
            throw ToolError.invalid("No \(ProjectWorkspace.filename) found for this project")
        }
        guard let name = arguments.taskName else {
            for name in workspace.configuration.tasks.keys.sorted() { print(name) }
            return
        }
        for task in try workspace.orderedTasks([name]) {
            try execute(task, workspace: workspace, extra: task == name ? arguments.applicationArguments : [])
        }
    }

    func runBeforeBuild(_ workspace: ProjectWorkspace) throws {
        for task in try workspace.orderedTasks(workspace.configuration.beforeBuild) {
            try execute(task, workspace: workspace, extra: [])
        }
    }

    func prepare(_ workspace: ProjectWorkspace) throws -> URL {
        let cache = workspace.directory.appendingPathComponent(".build/tasks")
        guard cache.resolvingSymlinksInPath().path.hasPrefix(workspace.directory.path + "/") else {
            throw ToolError.invalid("Project task cache must remain inside the workspace")
        }
        let tasks = workspace.configuration.tasks.filter { $0.value.platforms?.contains(.host) ?? true }
        let paths = Set(tasks.values.map(\.package)).sorted()
        let aliases = Dictionary(uniqueKeysWithValues: paths.enumerated().map { ($0.element, "ProjectTasks\($0.offset)") })
        let dependencies = try paths.map {
            ".package(name: \(Files.swiftLiteral(aliases[$0]!)), path: \(Files.swiftLiteral(try workspace.package($0).path)))"
        }
        var targets: [String] = [], products: [String] = []
        for name in tasks.keys.sorted() {
            let task = tasks[name]!, target = targetName(name)
            products.append(".executable(name: \(Files.swiftLiteral(target)), targets: [\(Files.swiftLiteral(target))])")
            targets.append(".executableTarget(name: \(Files.swiftLiteral(target)), dependencies: [.product(name: \(Files.swiftLiteral(task.product)), package: \(Files.swiftLiteral(aliases[task.package]!)))])")
            let source = """
            import Foundation
            import \(task.module)
            do { try \(task.entry)(Array(CommandLine.arguments.dropFirst())) }
            catch {
                FileHandle.standardError.write(Data((String(describing: error) + "\\n").utf8))
                exit(1)
            }
            """
            try write(source + "\n", to: cache.appendingPathComponent("Sources/\(target)/main.swift"))
        }
        let manifest = """
        // swift-tools-version: 6.4
        // Generated by Guava SDK from guava.workspace.json.
        import PackageDescription
        let package = Package(name: "GuavaProjectTasks", platforms: [.macOS(.v26)],
            products: [\(products.joined(separator: ",\n"))],
            dependencies: [\(dependencies.joined(separator: ",\n"))],
            targets: [\(targets.joined(separator: ",\n"))])
        """
        try write(manifest + "\n", to: cache.appendingPathComponent("Package.swift"))
        return cache
    }

    private func execute(_ name: String, workspace: ProjectWorkspace, extra: [String]) throws {
        let task = workspace.configuration.tasks[name]!
        guard task.platforms?.contains(.host) ?? true else {
            throw ToolError.invalid("Project task \(name) is unavailable on this host")
        }
        let cache = try prepare(workspace)
        let product = targetName(name)
        let build = SwiftPackage.command(directory: cache, configuration: arguments.configuration) + ["--skip-update"]
        var environment = try SwiftPackage.environment(root: sdk)
        environment["GUAVA_ROOT"] = workspace.directory.path
        let key = workspace.directory.path + ":" + name
        let active = environment["GUAVA_PROJECT_TASK_STACK", default: ""].split(separator: "\n").map(String.init)
        guard !active.contains(key) else { throw ToolError.invalid("Recursive project task invocation: \(name)") }
        environment["GUAVA_PROJECT_TASK_STACK"] = (active + [key]).joined(separator: "\n")
        try Shell.run(build + ["--product", product], at: workspace.directory, environment: environment, stdout: .standardError)
        let binaries = try Shell.run(build + ["--show-bin-path"], environment: environment, capture: true, quiet: true)
        let suffix = AppPlatform.host == .win ? ".exe" : ""
        try Shell.run([URL(fileURLWithPath: binaries).appendingPathComponent(product + suffix).path] + task.arguments + extra,
                      at: workspace.directory, environment: environment)
    }

    private func targetName(_ name: String) -> String { "GuavaTask_" + name.replacingOccurrences(of: "-", with: "_") }

    private func write(_ value: String, to file: URL) throws {
        if (try? String(contentsOf: file, encoding: .utf8)) != value { try Files.text(value, to: file) }
    }
}
